#!/usr/bin/env python3
"""Generate the packed perfect-play table for all Chomp boards up to 9 by 9."""

from itertools import combinations
from math import comb
from pathlib import Path
import sys

SIDE = 9
POSITION_COUNT = comb(2 * SIDE, SIDE)


def rank(rows):
    """Index a nonincreasing tuple of row lengths by its boundary path."""
    return sum(comb(length + i, i + 1) for i, length in enumerate(reversed(rows)))


def winning_positions():
    shapes = [tuple(reversed([point - i for i, point in enumerate(path)]))
              for path in combinations(range(2 * SIDE), SIDE)]
    winning = bytearray(POSITION_COUNT)
    # Every safe move removes at least one square, so its result is known
    # before we read it. A board containing only the poison is losing.
    for shape in sorted(shapes, key=sum):
        for row, width in enumerate(shape):
            for column in range(1 if row == 0 else 0, width):
                child = shape[:row] + tuple(min(length, column) for length in shape[row:])
                if not winning[rank(child)]:
                    winning[rank(shape)] = 1
                    break
            else:
                continue
            break
    packed = bytearray((POSITION_COUNT + 7) // 8)
    for index, outcome in enumerate(winning):
        packed[index // 8] |= outcome << (index % 8)
    return packed


def generate(output):
    packed = winning_positions()
    with output.open('w', encoding='ascii') as stream:
        stream.write('/* Generated by chomp_table.py. */\n')
        stream.write(f'enum {{ CHOMP_SIDE = {SIDE} }};\n')
        stream.write(f'static const uint16_t rank_term[{SIDE}][{2 * SIDE}] = {{\n')
        for i in range(SIDE):
            stream.write('    {' + ', '.join(str(comb(n, i + 1)) for n in range(2 * SIDE)) + '},\n')
        stream.write('};\n\n')
        stream.write(f'static const uint8_t winning_bits[{len(packed)}] = {{\n')
        for offset in range(0, len(packed), 16):
            line = ', '.join(f'0x{byte:02x}' for byte in packed[offset:offset + 16])
            stream.write(f'    {line},\n')
        stream.write('};\n')


if __name__ == '__main__':
    generate(Path(sys.argv[1]))
